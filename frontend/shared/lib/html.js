/**
 * [화면에 글자를 안전하게 표시하기 위한 공통 도구]
 *
 * 비개발자를 위한 설명:
 * - 이 프로그램의 화면은 웹페이지와 같은 방식으로 만들어집니다. 그래서 사용자가 입력한 글이나
 *   AI가 만든 문장 안에 `<b>` 같은 기호가 들어 있으면, 그것을 '글자'가 아니라 '명령'으로
 *   잘못 알아듣고 화면이 깨지거나 의도치 않은 동작을 할 수 있습니다.
 * - 아래 함수는 그런 기호들을 '보이기만 하는 안전한 글자'로 바꿔 줍니다.
 *   예) `<b>` → 화면에는 그대로 `<b>` 라는 글자로 보이고, 굵게 처리되지는 않습니다.
 *
 * - 예전에는 화면 파일마다 이 함수를 각자 복사해서 쓰고 있었고, 파일마다 처리 범위가 조금씩
 *   달랐습니다(어떤 파일은 따옴표를 처리하고 어떤 파일은 안 하는 식). 그래서 한곳으로 모으고
 *   가장 안전한 기준(따옴표까지 모두 처리) 하나로 통일했습니다.
 */

// 바꿔야 할 기호와, 바꾼 뒤의 안전한 표현을 짝지은 표
const HTML_ESCAPES = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

/**
 * 글자 속의 위험한 기호(& < > " ')를 모두 안전한 표현으로 바꾼다.
 *
 * 화면의 본문에 넣을 때든, 태그의 속성값(예: title="...")에 넣을 때든
 * 이 함수 하나만 쓰면 됩니다. 따옴표까지 처리하므로 두 경우 모두 안전합니다.
 * 사용자 눈에 보이는 모습은 원래 글자 그대로입니다.
 */
export function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, (character) => HTML_ESCAPES[character]);
}
